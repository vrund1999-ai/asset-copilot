import json
from pathlib import Path

from make_doc_questions import FIRST_ID, LEGACY_N, assign_ids, is_generated

QUESTIONS = Path(__file__).parent.parent / "evals" / "questions.jsonl"


def row(n, **extra):
    return {"id": f"q{n:03d}", **extra}


def test_is_generated_by_flag_or_legacy_block():
    assert is_generated(row(FIRST_ID))                       # legacy block, no flag
    assert is_generated(row(FIRST_ID + LEGACY_N - 1))
    assert not is_generated(row(FIRST_ID + LEGACY_N))        # hand-written, no flag
    assert is_generated(row(FIRST_ID + LEGACY_N + 50, generated=True))
    assert not is_generated(row(5))


def test_assign_ids_keeps_legacy_block_and_never_collides_with_hand_written():
    hand = [row(n) for n in (1, 2, 61, 62, 112, 140)]
    qs = [{"id": None} for _ in range(LEGACY_N + 3)]
    assign_ids(qs, hand)
    ids = [q["id"] for q in qs]
    assert ids[0] == "q031" and ids[LEGACY_N - 1] == "q060"
    assert ids[LEGACY_N:] == ["q141", "q142", "q143"]        # after the highest hand-written id
    assert not set(ids) & {r["id"] for r in hand}


def test_assign_ids_with_no_hand_written_rows():
    qs = [{"id": None} for _ in range(LEGACY_N + 2)]
    assign_ids(qs, [])
    assert [q["id"] for q in qs][LEGACY_N:] == ["q061", "q062"]


def test_committed_set_keeps_generated_rows_flagged_and_ids_unique():
    rows = [json.loads(ln) for ln in QUESTIONS.read_text(encoding="utf-8").splitlines() if ln.strip()]
    assert len({r["id"] for r in rows}) == len(rows)
    flagged = [r for r in rows if r.get("generated")]
    assert len(flagged) >= LEGACY_N
    # every doc-category row is generated by the script, never hand-written
    for r in rows:
        if r["category"] in ("document_lookup", "hybrid", "reconciliation"):
            assert r.get("generated"), r["id"]
